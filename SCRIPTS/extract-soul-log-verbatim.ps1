# SOUL LOG VERBATIM EXTRACTOR
# PURPOSE: Line-by-line verbatim capture of source files
# RULE: NO SUMMARIZING. NO PARAPHRASING. NO EDITING. INITIAL SOUL LOG = UNTOUCHED.
# FLAGS distinctive phrases inline for later DNA consolidation pass
# OUTPUT: SOUL-LOG file with line numbers + trailing index of flagged lines

param(
    [string]$SourceFile,
    [string]$OutputFile
)

if (-not $SourceFile -or -not (Test-Path $SourceFile)) {
    Write-Error "SOURCE FILE NOT FOUND: $SourceFile"
    exit 1
}

$sourceInfo = Get-Item $SourceFile
$outputDir = Split-Path $OutputFile -Parent
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir -Force | Out-Null }

# DNA FLAG KEYWORDS — phrases that mark high-signal Soul DNA moments
# These flag the line for later consolidation pass — they do NOT alter the verbatim content
$dnaFlags = @(
    'spy drone', 'probe droid', 'ledger', 'soul dna', 'magic chat', 'command station',
    'super saiyan', 'phoenix rising', 'reincarnate', 'gospel 444',
    'machine that builds', 'floodgates', 'capable operator', '2019', 'safe mode',
    'mormonism', 'truth principle', 'energy gate', 'drift', 'merkle', 'jedi',
    'agent 99', 'agent 98', 'agent 100', 'obi', 'anakin', 'mr hobbs', 'mr. hobbs',
    'survive', 'survival', 'vietnam', 'net pet', 'natural english', 'first 100 layers',
    '200 layers', 'rome protocol', 'shadow mode', 'audit the auditor', 'sentinel',
    'crash chat', 'stateless', 'pheromone', 'ant colony', 'data vault', 'hardened',
    'immutable', 'kill switch', 'padawan', 'master node', 'sentinel', 'swarm',
    'perplexity', 'claude', 'gpt', 'gemini', 'sonar', 'grok', 'deepseek',
    'blockchain', 'hash', 'sha', 'token', 'context window', 'cloudflare', 'workers',
    'six ai', '6 ai', 'six ais', '6 ais', 'golden dataset', 'data moat',
    'i am', "i'm", 'my system', 'my mission', 'my family', 'my students',
    'we are', 'we will', 'we can', 'we have', 'lets go', "let's go",
    'billion vnd', '1b vnd', 'mouse tier', 'tiger tier', 'cub tier'
)

Write-Host "SOUL LOG EXTRACTOR — VERBATIM MODE"
Write-Host "SOURCE: $($sourceInfo.Name) ($($sourceInfo.Length) bytes)"
Write-Host "OUTPUT: $OutputFile"
Write-Host "RULE: ZERO INTERPRETATION. ZERO SUMMARIZING. LINE BY LINE."
Write-Host ""

$lines = Get-Content $SourceFile -Encoding UTF8
$totalLines = $lines.Count
$flaggedLines = [System.Collections.Generic.List[object]]::new()

# Read raw text for character position tracking
$rawText = [System.IO.File]::ReadAllText($SourceFile, [System.Text.Encoding]::UTF8)
# Normalize CRLF → LF for char counting (matches human char count)
$rawNormalized = $rawText.Replace("`r`n", "`n").Replace("`r", "`n")
$totalChars = $rawNormalized.Length

$header = @"
# SOUL LOG — VERBATIM CAPTURE
# SOURCE: $($sourceInfo.Name)
# SOURCE_PATH: $SourceFile
# SOURCE_BYTES: $($sourceInfo.Length)
# SOURCE_LINES: $totalLines
# SOURCE_CHARS: $totalChars (LF-normalized — auditable from char 1 to $totalChars)
# EXTRACTED: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
# STATUS: UNTOUCHED — DO NOT EDIT THIS FILE
# RULE: This is the initial raw soul pass. Deduplication and consolidation happen LATER.
# FLAGGED lines are marked [DNA] inline — flags are for indexing only, content is verbatim.
# CHAR RANGE shown per line — proves zero gaps from char 1 to $totalChars
#
# NEXT STEP: Run consolidation pass against this file only AFTER full source corpus is captured.
# ============================================================

"@

$sb = [System.Text.StringBuilder]::new()
$sb.AppendLine($header) | Out-Null

$lineNum = 0
$charPos = 1  # Start at char 1

foreach ($line in $lines) {
    $lineNum++
    $padded = "{0:D5}" -f $lineNum
    $charStart = $charPos
    $charEnd = $charPos + $line.Length  # end = start + length of line content
    $charPos = $charEnd + 1  # +1 for the LF separator

    $charRange = "C$("{0:D6}" -f $charStart)-$("{0:D6}" -f $charEnd)"

    # Check for DNA flags
    $lowerLine = $line.ToLower()
    $flags = @()
    foreach ($flag in $dnaFlags) {
        if ($lowerLine.IndexOf($flag) -ge 0) {
            $flags += $flag.ToUpper().Replace(' ', '_')
        }
    }

    if ($flags.Count -gt 0) {
        $flagStr = "[DNA:" + ($flags -join "|") + "]"
        $sb.AppendLine("L$padded [$charRange] $flagStr $line") | Out-Null
        $flaggedLines.Add([PSCustomObject]@{
            LineNum    = $lineNum
            CharStart  = $charStart
            CharEnd    = $charEnd
            Flags      = $flags
            Content    = $line
        })
    } else {
        $sb.AppendLine("L$padded [$charRange] $line") | Out-Null
    }
}

$finalChar = $charPos - 1

# APPEND INDEX AT END — never inline, never alters verbatim section
$indexBlock = @"


# ============================================================
# DNA FLAG INDEX — FOR CONSOLIDATION PASS ONLY
# Total lines: $totalLines
# Flagged lines: $($flaggedLines.Count)
# Flag density: $([math]::Round($flaggedLines.Count / $totalLines * 100, 2))%
# ============================================================

"@
$sb.AppendLine($indexBlock) | Out-Null

foreach ($fl in $flaggedLines) {
    $flagStr = $fl.Flags -join " | "
    $preview = if ($fl.Content.Length -gt 120) { $fl.Content.Substring(0, 120) + "..." } else { $fl.Content }
    $sb.AppendLine("  L$("{0:D5}" -f $fl.LineNum) [$flagStr] $preview") | Out-Null
}

# Write output
[System.IO.File]::WriteAllText($OutputFile, $sb.ToString(), [System.Text.Encoding]::UTF8)

$outInfo = Get-Item $OutputFile
Write-Host "DONE."
Write-Host "OUTPUT: $($outInfo.Length) bytes"
Write-Host "LINES PROCESSED: $totalLines"
Write-Host "DNA FLAGS HIT: $($flaggedLines.Count) lines ($([math]::Round($flaggedLines.Count / $totalLines * 100, 2))%)"
Write-Host "STATUS: VERBATIM. UNTOUCHED. READY FOR LATER CONSOLIDATION PASS."
